import Foundation

struct LivePlaybackStream: Decodable {
  let id: String
  let title: String
  let uploaderName: String
  let uploaderURL: String
  let uploaderAvatarURL: String
  let thumbnailURL: String
  let description: String
  let duration: Int64
  let viewCount: Int64
  let likeCount: Int64
  let dislikeCount: Int64
  let startPosition: Int64
  let hlsURL: String
  let videoStreams: [LivePlaybackVideoSource]
  let audioStreams: [LivePlaybackAudioSource]
  let videoOnlyStreams: [LivePlaybackVideoSource]
  let subtitles: [LivePlaybackSubtitle]
  let chapters: [LivePlaybackChapter]
  let sponsorBlockSegments: [LivePlaybackSponsorSegment]
  let relatedStreams: [LiveVideoItem]
  let isLive: Bool
  let isPostLive: Bool
  let isLiveContent: Bool

  var allVideoSources: [LivePlaybackVideoSource] {
    var seen: Set<String> = []
    return (videoOnlyStreams + videoStreams).filter {
      seen.insert($0.selectionID).inserted
    }
  }

  private enum CodingKeys: String, CodingKey {
    case id, title, uploaderName, description, duration, viewCount
    case likeCount, dislikeCount, startPosition, videoStreams
    case audioStreams, videoOnlyStreams, subtitles, relatedStreams
    case isLive, isPostLive, isLiveContent
    case uploaderURL = "uploaderUrl"
    case uploaderAvatarURL = "uploaderAvatarUrl"
    case thumbnailURL = "thumbnailUrl"
    case hlsURL = "hlsUrl"
    case chapters = "streamSegments"
    case sponsorBlockSegments
  }
}

struct LivePlaybackVideoSource: Decodable, Hashable, Identifiable {
  let url: String
  let mimeType: String
  let resolution: String
  let bitrate: Int?
  let codec: String?
  let isVideoOnly: Bool
  let itag: Int
  let width: Int
  let height: Int
  let fps: Int
  let deliveryMethod: String
  let manifestURL: String?

  var id: String { selectionID }
  var selectionID: String { "\(itag):\(codec ?? "")" }

  var displayName: String {
    if !resolution.isEmpty { return resolution }
    if height > 0 { return "\(height)p" }
    return "Automatic"
  }

  var isAppleH264: Bool {
    mimeType.lowercased().hasPrefix("video/mp4")
      && codec?.lowercased().hasPrefix("avc1") == true
  }

  var isSABR: Bool {
    deliveryMethod.caseInsensitiveCompare("sabr") == .orderedSame
  }

  private enum CodingKeys: String, CodingKey {
    case url, mimeType, resolution, bitrate, codec, isVideoOnly
    case itag, width, height, fps, deliveryMethod
    case manifestURL = "manifestUrl"
  }
}

struct LivePlaybackAudioSource: Decodable, Hashable, Identifiable {
  let url: String
  let mimeType: String
  let bitrate: Int?
  let codec: String?
  let quality: String?
  let itag: Int
  let audioTrackID: String?
  let audioTrackName: String?
  let audioLocale: String?
  let isOriginal: Bool
  let deliveryMethod: String
  let manifestURL: String?

  var id: String {
    "\(itag):\(audioTrackID ?? ""):\(audioLocale ?? "")"
  }

  var displayName: String {
    if let audioTrackName, !audioTrackName.isEmpty {
      return audioTrackName
    }
    if let audioLocale, !audioLocale.isEmpty {
      return Locale.current.localizedString(
        forIdentifier: audioLocale
      ) ?? audioLocale
    }
    return isOriginal ? "Original" : "Default"
  }

  var isAppleAAC: Bool {
    mimeType.lowercased().hasPrefix("audio/mp4")
      && codec?.lowercased().hasPrefix("mp4a") == true
  }

  var isSABR: Bool {
    deliveryMethod.caseInsensitiveCompare("sabr") == .orderedSame
  }

  private enum CodingKeys: String, CodingKey {
    case url, mimeType, bitrate, codec, quality, itag
    case audioTrackName, audioLocale, isOriginal, deliveryMethod
    case audioTrackID = "audioTrackId"
    case manifestURL = "manifestUrl"
  }
}

struct LivePlaybackSubtitle: Decodable, Hashable, Identifiable {
  let url: String
  let mimeType: String
  let languageTag: String
  let displayLanguageName: String
  let isAutoGenerated: Bool

  var id: String {
    "\(languageTag):\(isAutoGenerated):\(url)"
  }

  var displayName: String {
    let suffix = isAutoGenerated ? " (automatic)" : ""
    return "\(displayLanguageName)\(suffix)"
  }
}

struct LivePlaybackChapter: Decodable, Hashable, Identifiable {
  let title: String
  let startTimeSeconds: Int
  let channelName: String?
  let url: String?
  let previewURL: String?

  var id: String { "\(startTimeSeconds):\(title)" }

  private enum CodingKeys: String, CodingKey {
    case title, startTimeSeconds, channelName, url
    case previewURL = "previewUrl"
  }
}

struct LivePlaybackSponsorSegment: Decodable, Hashable, Identifiable {
  let startTime: Double
  let endTime: Double
  let category: String
  let action: String

  var id: String { "\(category):\(startTime):\(endTime)" }
}

struct LivePlaybackPreferences: Equatable {
  var quality: String
  var videoItag: Int?
  var audioTrackID: String?
  var audioOnly: Bool
}

struct LivePlaybackPreparation {
  let stream: LivePlaybackStream
  let assetURL: URL
  let usesAuthenticatedLoader: Bool
  let video: LivePlaybackVideoSource?
  let audio: LivePlaybackAudioSource?
  let subtitles: [LivePlaybackSubtitle]
  let resumeTime: TimeInterval
  let isSABR: Bool
}

enum LivePlaybackFailure: LocalizedError {
  case unsupportedURL
  case noPlayableSource
  case invalidServerResource
  case invalidPlaylist
  case localPlaybackUnavailable
  case unavailableService

  var errorDescription: String? {
    switch self {
    case .unsupportedURL:
      return "This video URL is not supported by the selected instance."
    case .noPlayableSource:
      return "The instance returned no format that this Apple device can play."
    case .invalidServerResource:
      return "The player rejected a media resource outside the selected instance."
    case .invalidPlaylist:
      return "The instance returned an invalid media playlist."
    case .localPlaybackUnavailable:
      return "The secure local playback bridge could not be started."
    case .unavailableService:
      return "Playback is not available in this build."
    }
  }
}
