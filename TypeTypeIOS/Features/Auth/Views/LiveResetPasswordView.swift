import SwiftUI

struct LiveResetPasswordView: View {
  let service: ResetPasswordServiceProtocol
  @Environment(\.dismiss) private var dismiss
  @State private var token = ""
  @State private var password = ""
  @State private var confirmation = ""
  @State private var isSubmitting = false
  @State private var errorMessage: String?

  var body: some View {
    NavigationStack {
      Form {
        Section {
          TextField("Token", text: $token)
            .textInputAutocapitalization(.never)
            .autocorrectionDisabled()
        } header: { Text("Reset token").liveSectionHeader() } footer: {
          Text("Paste the reset token generated by your TypeType administrator.")
        }
        Section {
          SecureField("Password", text: $password)
          SecureField("Confirm password", text: $confirmation)
        } header: { Text("New password").liveSectionHeader() }
        if let errorMessage {
          Section {
            Label(
              errorMessage,
              systemImage: "exclamationmark.triangle.fill"
            )
            .foregroundStyle(.red)
          }
        }
      }
        .id(DemoTheme.renderToken)
        .listStyle(.insetGrouped)
        .scrollContentBackground(.hidden)
        .background(DemoTheme.background)
      .navigationTitle("Reset password")
      .navigationBarTitleDisplayMode(.inline)
      .toolbar {
        ToolbarItem(placement: .cancellationAction) {
          Button("Cancel") {
            dismiss()
          }
        }
        ToolbarItem(placement: .confirmationAction) {
          Button(isSubmitting ? "Updating…" : "Update") {
            Task {
              await submit()
            }
          }
          .disabled(!canSubmit)
        }
      }
    }
    .presentationDetents([.medium])
  }

  private var canSubmit: Bool {
    !token.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty
      && password.count >= 8
      && password == confirmation
      && !isSubmitting
  }

  private func submit() async {
    guard canSubmit else { return }
    isSubmitting = true
    errorMessage = nil
    do {
      try await service.reset(
        token: token.trimmingCharacters(in: .whitespacesAndNewlines),
        newPassword: password
      )
      dismiss()
    } catch {
      errorMessage = error.localizedDescription
    }
    isSubmitting = false
  }
}
