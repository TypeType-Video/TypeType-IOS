import XCTest
@testable import TypeTypeIOS

@MainActor
final class LiveNativeSubtitleTests: XCTestCase {
  private let english = LivePlaybackSubtitle(
    url: "https://www.youtube.com/api/timedtext?v=abc&lang=en&fmt=vtt",
    mimeType: "text/vtt",
    languageTag: "en",
    displayLanguageName: "English",
    isAutoGenerated: false
  )

  func testFullMetadataTracksAreUsedWhenTheStartListIsEmpty() {
    let chosen = LivePlayerController.nativeSubtitle(for: "en", available: [english], prepared: [])

    XCTAssertEqual(chosen, english)
  }

  func testStartListIsKeptUntilTheFullMetadataArrives() {
    let chosen = LivePlayerController.nativeSubtitle(for: "en", available: [], prepared: [english])

    XCTAssertEqual(chosen, english)
  }

  func testSelectedTrackLoadsItsCues() async {
    let service = RecoveryPlaybackService()
    service.subtitlePayload = Data(
      """
      WEBVTT

      00:00:01.000 --> 00:00:03.500
      First line

      00:00:04.000 --> 00:00:06.000
      Second line
      """.utf8
    )
    let track = LiveNativeSubtitleTrack()

    track.load(english, using: service)
    for _ in 0..<200 where track.cues.isEmpty {
      try? await Task.sleep(for: .milliseconds(10))
    }

    XCTAssertEqual(track.cues.map(\.text), ["First line", "Second line"])
    XCTAssertEqual(LiveWebVTT.cue(at: 2, in: track.cues)?.text, "First line")
    XCTAssertNil(track.failureID)
  }

  func testUnavailableTrackReportsAFailure() async {
    let track = LiveNativeSubtitleTrack()

    track.load(english, using: RecoveryPlaybackService())
    for _ in 0..<200 where track.failureID == nil {
      try? await Task.sleep(for: .milliseconds(10))
    }

    XCTAssertNotNil(track.failureID)
    XCTAssertTrue(track.cues.isEmpty)
  }
}
